_REF = re.compile(r"〔(K\d{2,3})〕")


def framework(role: Role, flags: Collection[str] = ()) -> str:
    """这个角色的专业提示词；flags 是档案里有的少见情况（injury、pregnancy、bp、diabetes、cardiac、poor），
    对应的规则才加进来。"""
    extra = [SPECIAL[f][role] for f in SPECIAL if f in flags and role in SPECIAL[f]]
    base = FRAMEWORKS.get(role, "")
    if not extra:
        return base
    return base + "\n【这个人的特殊情况】\n" + "\n".join(f"- {x}" for x in extra)


def framework_refs(role: Role, flags: Collection[str] = ()) -> tuple[str, ...]:
    """提示词里引用到的依据库编号：这些条目记为这一轮可以引用的依据。"""
    return tuple(dict.fromkeys(_REF.findall(framework(role, flags))))


def flags_of(risks: Collection[str], injured: bool, readiness: str = "") -> frozenset[str]:
    """档案里的风险和伤病 → 要加进提示词的少见情况。"""
    keys = set(risks)
    out = set()
    if keys & {"bp_crisis", "bp_high", "hypertension"}:
        out.add("bp")
    for k in ("pregnancy", "diabetes"):
        if k in keys:
            out.add(k)
    if keys & {"cardiac", "surgery"}:
        out.add("cardiac")
    if injured:
        out.add("injury")
    if readiness == "poor":
        out.add("poor")
    return frozenset(out)
