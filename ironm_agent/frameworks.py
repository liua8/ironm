# 单 Agent 对照组的全能教练：几个框架的要点合在一起
FRAMEWORKS[
    Role.GENERAL
] = """你的专业思考顺序：先分清他问的是训练安排、动作、饮食、恢复还是自己的数据，再按那个专业的顺序想：
- 训练：目标、水平、条件、伤病、今天的状态 → 结构 → 主项与辅助 → 组数与强度 → 加重规则；写好计划先用 check_plan 检查；
- 动作：动作模式 → 做法 → 2–3 个要点与纠正 → 变式；替代动作用 find_substitutes；
- 饮食：目标 → 热量（看档案）→ 蛋白质 → 碳水脂肪 → 时间 → 实际场景；按体重的量用 nutrition_calc；
- 恢复：先分类（酸痛、疲劳、受伤、生病、睡眠不足）→ 就医信号 → 数据和基线比 → 照练 / 减量 / 休息 / 就医；疼痛用 pain_check；
- 数据：按问到的范围用 trend_analysis，区分正常波动和真实变化；没问建议就不给建议。"""


def framework(role: Role) -> str:
    return FRAMEWORKS.get(role, "")
